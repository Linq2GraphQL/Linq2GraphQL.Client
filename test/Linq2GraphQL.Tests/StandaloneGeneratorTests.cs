using Linq2GraphQL.Generator;
using Shouldly;

namespace Linq2GraphQL.Tests;

/// <summary>
/// Standalone mode writes a copy of the runtime under &lt;namespace&gt;.Runtime next to the client. That the
/// copy compiles and works is covered by Linq2GraphQL.TestClientStandalone and Linq2GraphQL.Tests.Standalone;
/// these tests pin down what the generator emits.
/// </summary>
[Collection(GeneratorCollection.Name)]
public class StandaloneGeneratorTests
{
    private const string Sdl = """
        type Query { thing: Thing }
        type Subscription { thingAdded: Thing }
        type Thing { id: ID! }
        """;

    [Fact]
    public void Standalone_NothingReferencesTheRuntimePackages()
    {
        var entries = NewGenerator(standalone: true, includeSubscriptions: true).GenerateFromSdl(Sdl);

        entries.ShouldAllBe(e => !e.Content.Contains("Linq2GraphQL.Client"));
        Content(entries, "Client", "TestClient.cs").ShouldContain("using TestNs.Runtime;");
        Content(entries, "Runtime/Client", "GraphClient.cs").ShouldContain("namespace TestNs.Runtime;");
        Content(entries, "Runtime/Subscriptions", "WSClient.cs").ShouldContain("namespace TestNs.Runtime.Subscriptions;");
    }

    [Fact]
    public void Standalone_CopiesTheRuntime_WithoutAssemblyAttributes()
    {
        var entries = NewGenerator(standalone: true, includeSubscriptions: true).GenerateFromSdl(Sdl);
        var runtime = entries.Where(e => e.DirectoryName.StartsWith("Runtime")).ToList();

        runtime.ShouldContain(e => e.DirectoryName == "Runtime/Client/Visitors" && e.FileName == "QueryExpressionVisitor.cs");
        runtime.ShouldNotContain(e => e.FileName == "Assembly.cs");
        runtime.ShouldAllBe(e => !e.Content.Contains("[assembly:"));
        runtime.ShouldAllBe(e => e.Content.Contains("<auto-generated/>"));
    }

    [Fact]
    public void Standalone_WithoutSubscriptions_LeavesOutTheSubscriptionsRuntime()
    {
        var entries = NewGenerator(standalone: true, includeSubscriptions: false).GenerateFromSdl(Sdl);

        entries.ShouldNotContain(e => e.DirectoryName.StartsWith("Runtime/Subscriptions"));
        Content(entries, "Runtime", "RuntimeInfo.cs").ShouldNotContain("Websocket.Client");
    }

    [Fact]
    public void Standalone_RuntimeInfo_RecordsVersionAndPackages()
    {
        var info = Content(NewGenerator(standalone: true, includeSubscriptions: true).GenerateFromSdl(Sdl),
            "Runtime", "RuntimeInfo.cs");

        info.ShouldContain("namespace TestNs.Runtime;");
        info.ShouldMatch(@"public const string Version = ""\d+\.\d+\.\d+[^""+]*"";");
        info.ShouldContain("Microsoft.Extensions.Caching.Memory");
        info.ShouldContain("Microsoft.Extensions.Http");
        info.ShouldContain("Websocket.Client");
    }

    [Fact]
    public void PackageMode_IsUnchangedByStandalone()
    {
        var package = NewGenerator(standalone: false, includeSubscriptions: true).GenerateFromSdl(Sdl);
        var standalone = NewGenerator(standalone: true, includeSubscriptions: true).GenerateFromSdl(Sdl)
            .Where(e => !e.DirectoryName.StartsWith("Runtime"))
            .ToList();

        package.ShouldNotContain(e => e.DirectoryName.StartsWith("Runtime"));
        standalone.Select(e => e.FileName).ShouldBe(package.Select(e => e.FileName));
        for (var i = 0; i < package.Count; i++)
        {
            standalone[i].Content.ShouldBe(package[i].Content.Replace("Linq2GraphQL.Client", "TestNs.Runtime"));
        }
    }

    private static ClientGenerator NewGenerator(bool standalone, bool includeSubscriptions) =>
        new("TestNs", "TestClient", includeSubscriptions, EnumGeneratorStrategy.FailIfMissing, false, false,
            standalone: standalone);

    private static string Content(List<FileEntry> entries, string directory, string fileName) =>
        entries.Single(e => e.DirectoryName == directory && e.FileName == fileName).Content;
}
